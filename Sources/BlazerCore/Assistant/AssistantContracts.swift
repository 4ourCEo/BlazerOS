import Foundation

public enum AssistantFeature: String, Codable, Sendable, CaseIterable {
    case scanExplanation
    case coachAnswer
    case journalDraft
    case sessionDebrief
    case scanComparison
    case researchSuggestions
}

public enum AssistantOrigin: String, Codable, Sendable {
    case appleOnDevice
    case deterministicFallback
}

public enum AssistantAvailability: Equatable, Sendable {
    public enum Reason: Equatable, Sendable {
        case unsupportedOS
        case frameworkUnavailable
        case deviceNotEligible
        case appleIntelligenceNotEnabled
        case modelNotReady
        case localeUnsupported
        case failed(String)
    }

    case unknown
    case ready
    case unavailable(Reason)

    public var isReady: Bool {
        if case .ready = self { return true }
        return false
    }

    public var title: String {
        switch self {
        case .unknown: return "Checking on-device model"
        case .ready: return "Apple on-device model ready"
        case .unavailable: return "Basic explanation"
        }
    }

    public var detail: String {
        switch self {
        case .unknown:
            return "Availability has not been checked yet."
        case .ready:
            return "Responses are generated by Apple’s on-device system model. No network model is used."
        case .unavailable(let reason):
            switch reason {
            case .unsupportedOS:
                return "This iOS version does not provide Foundation Models."
            case .frameworkUnavailable:
                return "Foundation Models is not available in this build."
            case .deviceNotEligible:
                return "This device is not eligible for Apple Intelligence."
            case .appleIntelligenceNotEnabled:
                return "Apple Intelligence is turned off in Settings."
            case .modelNotReady:
                return "The on-device model is still downloading or preparing."
            case .localeUnsupported:
                return "The current language is not supported by the on-device model."
            case .failed(let message):
                return message
            }
        }
    }
}

public enum AssistantFailure: Error, Equatable, Sendable {
    case timedOut
    case cancelled
    case unavailable(AssistantAvailability.Reason)
    case contextTooLarge
    case invalidOutput([String])
    case generationFailed(String)

    public var reason: String {
        switch self {
        case .timedOut: return "timed out"
        case .cancelled: return "cancelled"
        case .unavailable(let reason): return "unavailable: \(reason)"
        case .contextTooLarge: return "context too large"
        case .invalidOutput(let issues): return "rejected output: \(issues.joined(separator: "; "))"
        case .generationFailed(let message): return "generation failed: \(message)"
        }
    }
}

/// Conservative accounting for one model request. `method` is "exact" only when Apple’s
/// tokenizer API returned a count; otherwise it is "estimated".
public struct ModelTokenEstimate: Sendable, Equatable {
    public var inputTokens: Int
    public var contextSize: Int
    public var outputReserve: Int
    public var safetyMargin: Int
    public var method: String
    public var omitted: [String]

    public init(
        inputTokens: Int,
        contextSize: Int,
        outputReserve: Int,
        safetyMargin: Int,
        method: String,
        omitted: [String] = []
    ) {
        self.inputTokens = inputTokens
        self.contextSize = contextSize
        self.outputReserve = outputReserve
        self.safetyMargin = safetyMargin
        self.method = method
        self.omitted = omitted
    }

    public var required: Int { inputTokens + outputReserve + safetyMargin }
    public var fits: Bool { required <= contextSize }
}

public enum ModelBudgetPolicy {
    /// Runtime fallback only. The production engine reads `SystemLanguageModel.contextSize`.
    public static let fallbackContextSize = 4_096
    public static let safetyMargin = 640

    public static func outputReserve(for feature: AssistantFeature) -> Int {
        switch feature {
        case .scanExplanation: return 420
        case .coachAnswer: return 420
        case .journalDraft: return 360
        case .sessionDebrief: return 500
        case .scanComparison: return 420
        case .researchSuggestions: return 700
        }
    }

    public static func toolReserve(for feature: AssistantFeature) -> Int {
        switch feature {
        case .scanExplanation: return 120
        case .coachAnswer: return 480
        case .journalDraft: return 180
        case .sessionDebrief: return 420
        case .scanComparison: return 240
        case .researchSuggestions: return 480
        }
    }
}


public struct AssistantDiagnostic: Codable, Equatable, Sendable, Identifiable {
    public var id: String
    public var feature: AssistantFeature
    public var origin: AssistantOrigin
    public var availability: String
    public var failure: String?
    public var latencyMs: Double
    public var schemaVersion: String
    public var promptVersion: String
    public var recordIDs: [String]
    public var validationIssues: [String]
    public var contextTokens: Int?
    public var contextLimit: Int?
    public var contextMethod: String?
    public var omitted: [String]?
    public var retryCount: Int?
    public var createdAt: Date

    public init(
        id: String = UUID().uuidString,
